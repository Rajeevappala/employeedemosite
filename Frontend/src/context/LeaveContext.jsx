const LeaveContext = createContext(null);

export function LeaveProvider({ children }) {
  const [leaveRequests, setLeaveRequests] = useState(INITIAL_LEAVE_REQUESTS);
  const [leaveBalances, setLeaveBalances] = useState(INITIAL_LEAVE_BALANCES);

  // 1. Add new leave request (from Employee or Admin)
  const addLeaveRequest = (newRequest) => {
    const nextId = `LR${String(leaveRequests.length + 1).padStart(3, '0')}`;
    const today = new Date().toISOString().split('T')[0];

    const formattedRequest = {
      id: nextId,
      employeeId: newRequest.employeeId || 'GP001',
      employeeName: newRequest.employeeName || 'Sai Rajeev Appala',
      department: newRequest.department || 'Technology',
      leaveType: newRequest.leaveType || 'PL',
      startDate: newRequest.startDate,
      endDate: newRequest.endDate,
      days: Number(newRequest.days) || 1,
      reason: newRequest.reason || '',
      status: 'Pending',
      requestedOn: today,
      reviewedBy: null,
      reviewedOn: null,
      adminComment: '',
    };

    setLeaveRequests((prev) => [formattedRequest, ...prev]);
    return formattedRequest;
  };

  // 2. Update request status (Approve / Reject / Review)
  const updateLeaveRequestStatus = (leaveId, newStatus, adminComment = '') => {
    const today = new Date().toISOString().split('T')[0];
    let approvedLeave = null;

    setLeaveRequests((prev) =>
      prev.map((req) => {
        if (req.id === leaveId) {
          if (newStatus === 'Approved') {
            approvedLeave = req;
          }
          return {
            ...req,
            status: newStatus,
            reviewedBy: 'Admin',
            reviewedOn: today,
            adminComment: adminComment || req.adminComment,
          };
        }
        return req;
      })
    );

    // If approved, update the employee's leave balance in state
    if (approvedLeave && newStatus === 'Approved') {
      const { employeeId, leaveType, days } = approvedLeave;
      setLeaveBalances((prev) =>
        prev.map((bal) => {
          if (bal.employeeId === employeeId) {
            if (leaveType === 'PL') {
              const newUsed = bal.plUsed + days;
              return {
                ...bal,
                plUsed: newUsed,
                plRemaining: Math.max(0, bal.plTotal - newUsed),
              };
            } else if (leaveType === 'Sick Leave') {
              const newUsed = bal.sickUsed + days;
              return {
                ...bal,
                sickUsed: newUsed,
                sickRemaining: Math.max(0, bal.sickTotal - newUsed),
              };
            } else if (leaveType === 'UPL') {
              return {
                ...bal,
                uplUsed: bal.uplUsed + days,
              };
            }
          }
          return bal;
        })
      );
    }
  };

  // 3. Cancel leave request
  const cancelLeaveRequest = (leaveId) => {
    setLeaveRequests((prev) =>
      prev.map((req) =>
        req.id === leaveId ? { ...req, status: 'Cancelled' } : req
      )
    );
  };

  return (
    <LeaveContext.Provider
      value={{
        leaveRequests,
        leaveBalances,
        addLeaveRequest,
        updateLeaveRequestStatus,
        cancelLeaveRequest,
      }}
    >
      {children}
    </LeaveContext.Provider>
  );
}

export default LeaveContext;
